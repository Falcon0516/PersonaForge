"use client";

import React, { useState, useMemo } from "react";
import { Copy, Check, Download, Zap, FileText } from "lucide-react";
import { BotConfig, Channel, compilePrompt } from "@personaforge/core";

interface PromptTabProps {
  config: BotConfig;
  channel: Channel;
}

export function PromptTab({ config, channel }: PromptTabProps) {
  const [copied, setCopied] = useState(false);
  const [hoveredLine, setHoveredLine] = useState<number | null>(null);

  const compiled = useMemo(() => {
    try {
      return compilePrompt(config, channel);
    } catch {
      return {
        prompt: "Error compiling prompt",
        trace: {},
        tokenEstimate: 0,
        sections: {} as any,
        warnings: [],
        droppedBlocks: [],
      };
    }
  }, [config, channel]);

  const lines = useMemo(() => compiled.prompt.split("\n"), [compiled.prompt]);

  const handleCopy = () => {
    navigator.clipboard.writeText(compiled.prompt);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([compiled.prompt], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${config.slug}-compiled-prompt.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const budgetPct = Math.min(100, Math.round((compiled.tokenEstimate / 4000) * 100));

  return (
    <div className="flex flex-col h-full bg-slate-950/80 font-mono text-xs">
      {/* Top Status Bar */}
      <div className="p-3 border-b border-slate-800 flex items-center justify-between gap-3 bg-slate-900/40">
        <div className="flex items-center gap-3">
          <div className="flex items-center gap-1.5 text-amber-400 font-semibold">
            <Zap className="w-3.5 h-3.5" />
            <span>{compiled.tokenEstimate} tokens</span>
          </div>
          <div className="hidden sm:flex items-center gap-2">
            <div className="w-20 bg-slate-800 h-1.5 rounded-full overflow-hidden">
              <div
                className={`h-full rounded-full transition-all ${
                  budgetPct > 85 ? "bg-rose-500" : budgetPct > 60 ? "bg-amber-500" : "bg-emerald-500"
                }`}
                style={{ width: `${budgetPct}%` }}
              />
            </div>
            <span className="text-[10px] text-slate-500">{budgetPct}% of 4k budget</span>
          </div>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleCopy}
            className="flex items-center gap-1.5 px-2.5 py-1 rounded-md bg-slate-800 hover:bg-slate-700 text-slate-300 border border-slate-700 transition"
          >
            {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
            <span>{copied ? "Copied" : "Copy"}</span>
          </button>
          <button
            onClick={handleDownload}
            className="p-1.5 rounded-md bg-slate-800 hover:bg-slate-700 text-slate-300 border border-slate-700 transition"
            title="Download Markdown"
          >
            <Download className="w-3.5 h-3.5" />
          </button>
        </div>
      </div>

      {/* Hovered Line Source Inspector Banner */}
      <div className="px-3.5 py-1.5 bg-slate-900/60 border-b border-slate-800 text-[11px] text-slate-400 flex items-center justify-between">
        <span className="flex items-center gap-1.5 truncate">
          <FileText className="w-3 h-3 text-indigo-400" />
          {hoveredLine && (compiled.trace as Record<number, string>)[hoveredLine] ? (
            <>
              Line {hoveredLine} generated by:{" "}
              <strong className="text-indigo-300 font-semibold">
                {(compiled.trace as Record<number, string>)[hoveredLine]}
              </strong>
            </>
          ) : (
            "Hover any line to view which block generated it"
          )}
        </span>
        <span className="text-slate-500 font-mono text-[10px]">
          {lines.length} lines &bull; {channel}
        </span>
      </div>

      {/* Code Display Area */}
      <div className="flex-1 overflow-y-auto p-3 leading-relaxed select-text">
        <table className="w-full border-collapse">
          <tbody>
            {lines.map((line, idx) => {
              const lineNum = idx + 1;
              const sourceBlock = (compiled.trace as Record<number, string>)[lineNum];
              const isSectionHeader = line.startsWith("## ");
              const isHovered = hoveredLine === lineNum;

              return (
                <tr
                  key={lineNum}
                  onMouseEnter={() => setHoveredLine(lineNum)}
                  onMouseLeave={() => setHoveredLine(null)}
                  className={`transition-colors ${
                    isHovered
                      ? "bg-indigo-950/40"
                      : isSectionHeader
                      ? "bg-slate-900/30"
                      : "hover:bg-slate-900/20"
                  }`}
                >
                  <td className="w-10 pr-3 text-right text-slate-600 select-none font-mono text-[11px]">
                    {lineNum}
                  </td>
                  <td
                    className={`pl-2 font-mono text-xs whitespace-pre-wrap break-all ${
                      isSectionHeader
                        ? "text-indigo-400 font-bold pt-2 pb-1"
                        : "text-slate-300"
                    }`}
                  >
                    {line || <span className="opacity-0">.</span>}
                  </td>
                  <td className="w-28 pl-2 text-right select-none">
                    {sourceBlock && (
                      <span className="text-[9px] px-1.5 py-0.5 rounded bg-slate-900 text-slate-500 border border-slate-800/80 truncate block max-w-full">
                        {sourceBlock}
                      </span>
                    )}
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>
    </div>
  );
}
